def _children(stack: cdk.Stack, prefix: str) -> list[IConstruct]:
    found = [child for child in stack.node.children if child.node.id.startswith(prefix)]
    if not found:
        raise LookupError(f"Expected a {prefix} construct in {stack.stack_name}.")
    return found


def framework_helper_exceptions(runtime: cdk.Stack, app: cdk.Stack) -> None:
    """Document findings in CDK and deploy-time-build helper resources we do not author."""
    helper = [
        NagPackSuppression(
            id="AwsSolutions-IAM4",
            reason="Deployment-only helper uses the standard AWS Lambda logging policy.",
        ),
        NagPackSuppression(
            id="AwsSolutions-IAM5",
            reason="Generated by CDK grants for the bootstrap asset bucket and the target website bucket; used only during deployment.",
        ),
        NagPackSuppression(
            id="AwsSolutions-L1",
            reason="Runtime is chosen by the CDK or deploy-time-build library and updated with the pinned library version.",
        ),
    ]
    for child in _children(app, "Custom::CDKBucketDeployment") + _children(
        runtime, "DeployTimeBuildCustomResourceHandler"
    ):
        NagSuppressions.add_resource_suppressions(child, helper, apply_to_children=True)
    NagSuppressions.add_resource_suppressions(
        _children(runtime, "ContainerImageBuildArm64")[0],
        [
            NagPackSuppression(
                id="AwsSolutions-IAM4",
                reason="CodeBuild pulls the Dockerfile's public base image from Amazon ECR Public using the AWS read-only policy.",
            ),
            NagPackSuppression(
                id="AwsSolutions-IAM5",
                reason="Generated CodeBuild log, report and source-asset grants plus ECR authorization, which has no resource-level form.",
            ),
            NagPackSuppression(
                id="AwsSolutions-CB4",
                reason="The project only builds and pushes one image; there are no build artifacts to encrypt with a customer key.",
            ),
        ],
        apply_to_children=True,
    )
